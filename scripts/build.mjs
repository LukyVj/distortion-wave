// Builds dist/ (ESM, minified ESM, IIFE for <script> tags) and demo/standalone.html
// (one self-contained file that opens straight from disk, no server needed).
import { build } from 'esbuild';
import { minify } from 'terser';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { glslMin } from './glsl-min.mjs';

const banner = { js: '/*! distortion-wave · MIT © Lucas Bonomi · https://github.com/LukyVj/distortion-wave */' };
const common = { entryPoints: ['src/index.js'], bundle: true, target: 'es2022', banner, logLevel: 'warning', plugins: [glslMin] };

// Minified builds: esbuild minifies, then Terser squeezes harder (≈ -0.2 kB gzipped on the core). No pure_getters:
// the code reads DOM properties to force a reflow. The /*! banner stays.
const terser = () => ({ ecma: 2022, compress: { passes: 3, unsafe_arrows: true, unsafe_methods: true }, mangle: true, format: { comments: /^!/ } });   // fresh each time: Terser writes into its options
async function min(opts) {
  const [out] = (await build({ ...opts, minify: true, write: false })).outputFiles;
  const { code } = await minify(out.text, { ...terser(), module: opts.format === 'esm' });
  await writeFile(opts.outfile, `${code}\n`);
}

await mkdir('dist', { recursive: true });
await build({ ...common, format: 'esm', outfile: 'dist/distortion-wave.js' });
await min({ ...common, format: 'esm', outfile: 'dist/distortion-wave.min.js' });
await min({ ...common, format: 'iife', globalName: 'DistortionWave', outfile: 'dist/distortion-wave.iife.min.js' });
// Effects ship as their own entries, so the core stays as light when they aren't used.
const FX = { electric: 'Electric', pixel: 'Pixel', glass: 'Glass' };
for (const [name, Global] of Object.entries(FX)) {
  const fx = { ...common, entryPoints: [`src/effects/${name}.js`] };
  await build({ ...fx, format: 'esm', outfile: `dist/${name}.js` });
  await min({ ...fx, format: 'esm', outfile: `dist/${name}.min.js` });
  await min({ ...fx, format: 'iife', globalName: `DistortionWave${Global}`, outfile: `dist/${name}.iife.min.js` });
}

// Standalone demo: inline the IIFE build and turn the module import into a destructure.
const html = await readFile('demo/index.html', 'utf8');
const iife = await readFile('dist/distortion-wave.iife.min.js', 'utf8');
const standalone = html
  .replace(/import \{([^}]+)\} from '\.\.\/src\/index\.js';/, 'const {$1} = window.DistortionWave;')
  .replace('<script type="module">', () => `<script>${iife}</script>\n<script type="module">`);   // a function: the minified code may contain $' or $&
if (standalone === html) throw new Error('demo import line not found');
await writeFile('demo/standalone.html', standalone);

// Offline copy of the CodePen example (examples/ui-kit): same HTML/CSS/JS, library inlined.
const kit = (f) => readFile(`examples/ui-kit/${f}`, 'utf8');
const [kHtml, kCss, kJs] = await Promise.all([kit('index.html'), kit('style.css'), kit('script.js')]);
const kitJs = kJs.replace(/import \{([^}]+)\} from '[^']+';/, (_, names) => `const {${names.replace(/\s+as\s+/g, ': ')}} = window.DistortionWave;`);
if (kitJs === kJs) throw new Error('ui-kit import line not found');
await writeFile('examples/ui-kit/standalone.html', `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>distortion-wave · UI kit</title>
<style>
${kCss}</style>
</head>
<body>
${kHtml}<script>${iife}</script>
<script type="module">
${kitJs}document.body.dataset.ready = '1';
</script>
</body>
</html>
`);

const sizes = await Promise.all(['dist/distortion-wave.js', 'dist/distortion-wave.min.js', 'dist/distortion-wave.iife.min.js', ...Object.keys(FX).map((n) => `dist/${n}.min.js`)].map(async (f) => `${f} ${((await readFile(f)).length / 1024).toFixed(1)} kB`));
console.log(sizes.join('\n'));

// CodePen copy of the React example (examples/react): JSX through CodePen's Babel, React from esm.sh.
const rx = (f) => readFile(`examples/react/src/${f}`, 'utf8');
const [hookSrc, appSrc] = await Promise.all([rx('useWave.js'), rx('App.jsx')]);
const body = (src) => src.replace(/^import .*\n/gm, '').replace(/^export /gm, '').trim();
await writeFile('examples/react/codepen.jsx', [
  '// CodePen version of examples/react (JS preprocessor: Babel). Generated by scripts/build.mjs.',
  "import React, { useCallback, useMemo, useRef, useState } from 'https://esm.sh/react@19';",
  "import { flushSync } from 'https://esm.sh/react-dom@19';",
  "import { createRoot } from 'https://esm.sh/react-dom@19/client';",
  "import { distortionWave } from 'https://cdn.jsdelivr.net/npm/distortion-wave@0.2/+esm';",
  '', body(hookSrc), '', body(appSrc), '',
  "createRoot(document.getElementById('root')).render(<App />);", '',
].join('\n'));
